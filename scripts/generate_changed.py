#!/usr/bin/env python3
"""Generate the FHEM update summary and retain the historical changelog."""

import json
import re
import sys
import textwrap
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAX_SUMMARY_LINES = 25
WIDTH = 79


def render(notes_dir: Path) -> str:
    files = sorted(notes_dir.glob("*.json"), reverse=True)
    if not files:
        raise ValueError(f"No release notes found in {notes_dir}")
    sections = []
    for path in files:
        entry = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(entry, dict) or set(entry) != {"date", "version", "title", "changes"}:
            raise ValueError(f"Invalid fields in {path}")
        day, version, title, changes = (
            entry["date"], entry["version"], entry["title"], entry["changes"]
        )
        if not isinstance(day, str) or date.fromisoformat(day).isoformat() != day:
            raise ValueError(f"Invalid date in {path}")
        if not path.name.startswith(day + "-"):
            raise ValueError(f"Filename must start with the entry date in {path}")
        if not isinstance(version, str) or not re.fullmatch(r"\d+\.\d+\.\d+(?:-dev)?", version):
            raise ValueError(f"Invalid version in {path}")
        if not isinstance(title, str) or not title.strip() or "\n" in title or "\r" in title:
            raise ValueError(f"Invalid title in {path}")
        if not isinstance(changes, list) or not changes or any(
            not isinstance(item, str) or not item.strip() or "\n" in item or "\r" in item
            for item in changes
        ):
            raise ValueError(f"Invalid changes in {path}")
        lines = textwrap.wrap(
            f"{day} - {version}: {title}", width=WIDTH,
            break_long_words=False, break_on_hyphens=False,
        )
        for item in changes:
            lines.extend(textwrap.wrap(
                f"- {item}", width=WIDTH, subsequent_indent="  ",
                break_long_words=False, break_on_hyphens=False,
            ))
        if len(lines) > MAX_SUMMARY_LINES:
            raise ValueError(f"Summary in {path} exceeds {MAX_SUMMARY_LINES} lines")
        if any(len(line) > WIDTH or not line.isascii() for line in lines):
            raise ValueError(f"Summary in {path} must be ASCII and at most {WIDTH} columns")
        sections.append("\n".join(lines))
    archive = (notes_dir / "archive.txt").read_text(encoding="utf-8").strip("\n")
    if not archive:
        raise ValueError("Changelog archive is empty")
    return (
        "# Generated by scripts/generate_changed.py; edit release-notes instead.\n"
        + "\n\n".join(sections)
        + "\n\n"
        + archive
        + "\n"
    )


def main() -> None:
    content = render(ROOT / "release-notes")
    output = ROOT / "CHANGED"
    if sys.argv[1:] == ["--check"]:
        if output.read_text(encoding="utf-8") != content:
            raise SystemExit("CHANGED is out of date; run scripts/generate_changed.py")
    elif not sys.argv[1:]:
        output.write_text(content, encoding="utf-8")
    else:
        raise SystemExit("Usage: python3 scripts/generate_changed.py [--check]")


if __name__ == "__main__":
    main()
