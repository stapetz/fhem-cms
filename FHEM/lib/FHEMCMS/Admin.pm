package main;

use strict;
use warnings;
use Cwd qw(abs_path);
use Digest::SHA qw(sha256_hex);
use File::Spec;
use JSON::PP ();

our (%defs, %attr, %FW_webArgs, @FW_httpheader, $FW_chash, $FW_wname, %FHEMCMS_PURGED);
my $ADMIN_JSON = JSON::PP->new->utf8->canonical;
my %ADMIN_SHARED = map { $_ => 1 } qw(js css components media fonts images);

sub FHEMCMS_AdminTree {
    my ($path, $relative, $files, $budget) = @_;
    return 'Verzeichnisstruktur ist zu tief; manuelle Pruefung erforderlich'
        if (scalar(split('/', $relative)) > 24);
    return 'Zu viele Dateien; manuelle Pruefung erforderlich' if (--${$budget} < 0);
    my @stat = lstat($path);
    return 'Dateistruktur konnte nicht geprueft werden' if (!@stat);
    return 'Symlinks werden nicht bereinigt' if (-l _);
    push(@{$files}, {path => $relative, directory => -d _ ? JSON::PP::true : JSON::PP::false,
        stamp => join(':', @stat[0, 1, 2, 7, 9, 10])});
    return undef if (!-d _);
    opendir(my $dh, $path) or return 'Verzeichnis konnte nicht gelesen werden';
    my @entries = sort grep { $_ ne '.' && $_ ne '..' } readdir($dh);
    closedir($dh);
    for my $entry (@entries) {
        return 'Ungueltiger Dateiname; manuelle Pruefung erforderlich' if ($entry =~ /[\x00-\x1f\x7f]/);
        my $error = FHEMCMS_AdminTree(File::Spec->catfile($path, $entry),
            "$relative/$entry", $files, $budget);
        return $error if (defined($error));
    }
    return undef;
}

sub FHEMCMS_AdminInventory {
    return (undef, 'Zugriff verweigert') if (!Authorized($FW_chash, 'cmd', 'get'));
    return (undef, 'FHEM modpath ist nicht gesetzt')
        if (!defined($attr{global}{modpath}) || $attr{global}{modpath} eq '');
    my $root = abs_path($attr{global}{modpath});
    return (undef, 'FHEM modpath ist ungueltig') if (!defined($root) || !-d $root);
    my @roots = (
        ['fhem-cms-data', File::Spec->catdir($root, 'fhem-cms-data')],
        ['www/fhem-cms', File::Spec->catdir($root, 'www', 'fhem-cms')],
    );
    my %names = map { $_ => 1 } grep { ($defs{$_}{TYPE} // '') eq 'FHEMCMS' } keys %defs;
    for my $pair (@roots) {
        my ($label, $path) = @{$pair};
        next if (!-e $path && !-l $path);
        return (undef, "Unsicheres Stammverzeichnis: $label")
            if (-l $path || !-d $path || !FHEMCMS_IsChildPath(abs_path($path), $root));
        opendir(my $dh, $path) or return (undef, "Stammverzeichnis nicht lesbar: $label");
        my @entries = readdir($dh);
        closedir($dh);
        for my $name (@entries) {
            next if (!FHEMCMS_ValidName($name) || ($label eq 'www/fhem-cms' && $ADMIN_SHARED{$name}));
            my $dir = File::Spec->catdir($path, $name);
            $names{$name} = 1 if (-d $dir || -l $dir);
        }
    }
    return (undef, 'Zu viele CMS-Verzeichnisse; manuelle Pruefung erforderlich') if (keys(%names) > 500);
    my @items;
    my $budget = 10000;
    for my $name (sort keys %names) {
        next if (!FHEMCMS_ValidName($name) || !Authorized($FW_chash, 'devicename', $name));
        my $exists = exists($defs{$name});
        my $active = $exists && ($defs{$name}{TYPE} // '') eq 'FHEMCMS';
        my @files;
        my $blocked = $ADMIN_SHARED{$name} ? 'Gemeinsames Assetverzeichnis ist geschuetzt' : undef;
        for my $pair (@roots) {
            my ($label, $path) = @{$pair};
            my $dir = File::Spec->catdir($path, $name);
            next if (!-e $dir && !-l $dir);
            my $error = FHEMCMS_AdminTree($dir, "$label/$name", \@files, \$budget);
            $blocked //= $error;
        }
        $blocked //= 'Name wird von einem anderen FHEM-Device verwendet' if ($exists && !$active);
        if (!$active && !defined($blocked)) {
            my $dataDir = File::Spec->catdir($roots[0][1], $name);
            my $index = File::Spec->catfile($roots[1][1], $name, 'index.html');
            my $owned = 0;
            if (-f $index && !-l $index) {
                my ($text, $error) = FHEMCMS_ReadFile($index);
                $owned = !defined($error) && index($text, '<!-- generated by 01_FHEMCMS.pm; do not edit -->') >= 0;
            }
            if (!$owned && -f File::Spec->catfile($dataDir, 'config.json')) {
                my ($format, $error) = FHEMCMS_ReadLayoutFormat($dataDir);
                $owned = defined($format) && !defined($error);
            }
            $blocked = 'Keine eindeutig zuordenbaren CMS-Daten; manuelle Pruefung erforderlich' if (!$owned);
        }
        $blocked //= FHEMCMS_Purge($name, 1) if (!defined($blocked));
        my $canDelete = Authorized($FW_chash, 'cmd', 'set') && Authorized($FW_chash, 'cmd', 'delete');
        $blocked //= 'Keine Berechtigung fuer set und delete' if (!$canDelete);
        push(@items, {name => $name, kind => $active ? 'device' : 'orphan', files => \@files,
            blocked => $blocked, identity => $active ? ($defs{$name}{NR} // '') : ''});
    }
    my $token = sha256_hex($ADMIN_JSON->encode(\@items));
    return ({items => \@items, token => $token}, undef);
}

sub FHEMCMS_AdminExecute {
    my ($request) = @_;
    return {error => 'Ungueltige Verwaltungsanfrage'} if (ref($request) ne 'HASH'
        || join(',', sort keys %{$request}) ne 'confirmation,items,token'
        || ref($request->{items}) ne 'ARRAY' || !@{$request->{items}} || @{$request->{items}} > 20
        || ref($request->{token}) || ($request->{token} // '') !~ /\A[0-9a-f]{64}\z/
        || ref($request->{confirmation}) || ($request->{confirmation} // '') ne 'DELETE');
    my ($inventory, $error) = FHEMCMS_AdminInventory();
    return {error => $error} if (defined($error));
    return {error => 'Bestand ist veraltet; bitte aktualisieren und erneut bestaetigen'}
        if ($request->{token} ne $inventory->{token});
    my %current = map { $_->{name} => $_ } @{$inventory->{items}};
    my %seen;
    for my $item (@{$request->{items}}) {
        return {error => 'Ungueltige CMS-Auswahl'} if (ref($item) ne 'HASH'
            || join(',', sort keys %{$item}) ne 'kind,name' || ref($item->{name}) || ref($item->{kind})
            || !FHEMCMS_ValidName($item->{name}) || $seen{$item->{name}}++
            || !$current{$item->{name}} || ($item->{kind} // '') ne $current{$item->{name}}{kind});
        return {error => $current{$item->{name}}{blocked}} if (defined($current{$item->{name}}{blocked}));
    }
    my @results;
    for my $item (@{$request->{items}}) {
        my $name = $item->{name};
        my $purgeError = FHEMCMS_Purge($name);
        my $deleteError;
        if (!defined($purgeError) && $item->{kind} eq 'device') {
            $FHEMCMS_PURGED{$name} = 1;
            $defs{$name}{STATE} = 'purged';
            $deleteError = CommandDelete($FW_chash, $name);
        }
        my $failure = $purgeError // $deleteError;
        Log3('FHEMCMS', defined($failure) ? 1 : 3,
            "FHEMCMS: Verwaltung $item->{kind} $name " . (defined($failure) ? 'fehlgeschlagen' : 'abgeschlossen'));
        push(@results, {name => $name, kind => $item->{kind},
            ok => defined($failure) ? JSON::PP::false : JSON::PP::true,
            message => $failure // ($item->{kind} eq 'device'
                ? 'Purge und Delete abgeschlossen' : 'Verwaiste CMS-Dateien bereinigt')});
    }
    return {results => \@results};
}

sub FHEMCMS_AdminEndpoint {
    my ($arg) = @_;
    return ('application/json; charset=utf-8', $ADMIN_JSON->encode({error => 'Ungueltiger Verwaltungspfad'}))
        if ($arg !~ m{\A/fhemcms-admin(?:\?|&|\z)});
    my $operation = $FW_webArgs{op} // 'list';
    my $result;
    if ($operation eq 'list') {
        my ($inventory, $error) = FHEMCMS_AdminInventory();
        $result = defined($error) ? {error => $error} : $inventory;
    } elsif ($operation eq 'delete') {
        my ($method) = split(/\s+/, $FW_httpheader[0] // '');
        my $expected = $defs{$FW_wname}{CSRFTOKEN};
        my $csrfDisabled = ($attr{$FW_wname}{csrfToken} // '') eq 'none';
        if ($method ne 'POST' || (!$csrfDisabled && (!defined($expected) || $expected eq ''
            || ($FW_webArgs{fwcsrf} // '') ne $expected))) {
            $result = {error => 'POST mit gueltigem FHEMWEB-CSRF-Token erforderlich'};
        } elsif (length($FW_webArgs{payload} // '') > 16384) {
            $result = {error => 'Verwaltungsanfrage ist zu gross'};
        } else {
            my $request = eval { JSON::PP->new->decode($FW_webArgs{payload} // '') };
            my $invalid = $@ ? 1 : 0;
            $result = $invalid ? {error => 'Ungueltiges Verwaltungs-JSON'} : FHEMCMS_AdminExecute($request);
        }
    } else {
        $result = {error => 'Unbekannte Verwaltungsaktion'};
    }
    Log3('FHEMCMS', 2, 'FHEMCMS: Verwaltungsanfrage abgewiesen') if ($result->{error});
    return ('application/json; charset=utf-8', $ADMIN_JSON->encode($result));
}

1;
